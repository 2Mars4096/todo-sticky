"""Build Flutter's synchronous interface lookup from the shared product catalogs."""
import json
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parents[1]
directory = root / 'phone/assets/interface'
tags = ['zh-Hans', 'zh-Hant', 'yue', 'ja', 'ko', 'fr', 'de', 'es', 'pt']
columns = [json.loads((directory / (tag + '.json')).read_text()) for tag in tags]
keys = json.loads((directory / 'keys.json').read_text())
for tag,column in zip(tags,columns):
    missing,extra = set(keys)-set(column), set(column)-set(keys)
    empty = [key for key in keys if not isinstance(column.get(key),str) or not column.get(key,'').strip()]
    if missing or extra or empty:
        raise ValueError(f'{tag}: {len(missing)} missing keys, {len(extra)} obsolete keys, {len(empty)} empty values')

def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
lines = ['// Generated from phone/assets/interface by scripts/sync-interface.py.',
         'const interfaceTags = <String>[' + ', '.join(map(dart, tags)) + '];',
         'const interfaceRows = <String, List<String>>{']
for key in keys:
    row = [column[key] for column in columns]
    for tag, text in zip(tags, row):
        if sorted(re.findall(r'\{\d+\}', text)) != sorted(re.findall(r'\{\d+\}', key)):
            raise ValueError(f'{tag}: placeholders for {key}')
    lines.append('  ' + dart(key) + ': [' + ', '.join(map(dart, row)) + '],')
lines.append('};')
(root / 'phone/lib/interface_labels.dart').write_text('\n'.join(lines)+'\n')

# Standalone legacy sign-in is served without the Vite runtime. Bundle only its own public copy.
signin_page = (root/'backend/signin.html').read_text()
signin_js = (root/'backend/signin.js').read_text()
signin_keys = set(re.findall(r'data-interface>([^<>]+)<', signin_page))
signin_keys.update(json.loads(value) for value in re.findall(r'ui\(("(?:\\.|[^"\\])*")\)', signin_js))
signin = {tag:{key:col.get(key,key) for key in sorted(signin_keys)} for tag,col in zip(tags,columns)}
runtime = '''export function signInInterface(requested) {
  const raw=requested || (typeof navigator === 'undefined' ? 'en' : navigator.language);
  const parts=String(raw).toLowerCase().split('-');
  const tag=parts.includes('yue') ? 'yue' : parts[0]==='zh' ? (!parts.includes('hans') && parts.some(p=>['hant','hk','mo','tw'].includes(p))?'zh-Hant':'zh-Hans') : parts[0];
  const labels=translations[tag] || {};
  document.documentElement.lang=translations[tag]?tag:'en';
  const ui=key=>labels[key] || key;
  document.querySelectorAll('[data-interface]').forEach(el=>{el.textContent=ui(el.textContent)});
  return ui;
}
'''
(root/'backend/signin-interface.js').write_text('// Generated by scripts/sync-interface.py\nconst translations='+json.dumps(signin,ensure_ascii=False,separators=(',',':'))+';\n'+runtime)

# The host may import the plugin source entry as well as its built ESM. Keep its labels inside the package.
plugin_keys = json.loads(subprocess.check_output(['node', str(root/'scripts/audit-interface.cjs'), '--plugin-keys']))
parts = ['// Generated from Dockit interface catalogs.', 'export const interfaceTags: string[] = '+json.dumps(tags)+';', 'export const interfaceRows: Record<string,string[]> = {']
for key in sorted(plugin_keys):
    parts.append(json.dumps(key,ensure_ascii=False)+':'+json.dumps([col.get(key,key) for col in columns],ensure_ascii=False)+',')
(root/'plugin/src/interfaceLabels.ts').write_text('\n'.join(parts+['};','']))
