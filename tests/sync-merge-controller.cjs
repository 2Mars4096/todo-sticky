const assert = require('node:assert/strict')
const { fixture } = require('./sync-frequency.cjs')
const goals = (ids, texts = {}) => ({targets:ids.map(id=>({id,text:texts[id]??id,done:false})),recurring:[]})
;(async () => {
  let f = await fixture({ recoverServer:true })
  assert.equal(f.render().server, 'https://sync.example.test', 'A published build restores its existing enabled service without compiled defaults')
  f.hooks.goals = goals(['old','a']); f.baseline('goals',goals(['old'])); f.remote('goals',goals(['old','b'])); f.render()
  f.failPut(true); await f.render().sync()
  assert.match(f.render().error,/Offline upload/)
  assert.deepEqual(JSON.parse(JSON.stringify(f.hooks.goals)),goals(['old','a','b']),'Merge retained locally before failed upload')
  assert.equal(f.render().recovery.length,1,'Exact originals retained before applying an automatic merge')
  f.failPut(false); await f.render().sync()
  assert.equal(f.render().error,null)
  assert.equal(f.uploads.length,2)
  assert.equal(f.uploads[0].mutationId,f.uploads[1].mutationId,'Interrupted merge reuses pending mutation identity')
  f.dispose()

  f=await fixture()
  f.hooks.goals=goals(['a','b','x'],{a:'Local A',b:'Local B'}); f.baseline('goals',goals(['a','b'])); f.remote('goals',goals(['a','b','y'],{a:'Cloud A',b:'Cloud B'})); f.render()
  await f.render().sync()
  let review=f.render().conflicts[0]
  assert.equal(review.merge.issues.length,2)
  const fingerprint=require('./helpers/load-typescript.cjs')('src/syncConflicts.ts').conflictFingerprint(review)
  f.failPut(true)
  await f.render().resolveItems('goals',{'/targets/a/text':'local','/targets/b/text':'cloud'},fingerprint)
  assert.match(f.render().error,/Offline upload/)
  f.failPut(false); await f.render().sync()
  assert.equal(f.render().error,null)
  assert.equal(f.uploads[0].mutationId,f.uploads[1].mutationId,'Retry accepted item choices without requiring a second review')
  assert.deepEqual(JSON.parse(JSON.stringify(f.hooks.goals)),goals(['a','b','x','y'],{a:'Local A',b:'Cloud B'}),'Per-item choices preserve independent additions')
  f.dispose()

  f=await fixture()
  f.hooks.goals=goals(['old','a']); f.baseline('goals',goals(['old'])); f.remote('goals',goals(['old','b'])); f.render()
  f.hooks.applyGoals=async()=>{throw Error('Fixture disk full')}
  await f.render().sync()
  assert.match(f.render().error,/disk full/); assert.equal(f.uploads.length,0,'Never upload a merge whose local save failed')
  f.dispose()
  console.log('Passed service restoration, durable automatic merge, interrupted retry identity, exact originals, individual choices and failed-save containment')
})().catch(error=>{console.error(error);process.exit(1)})
