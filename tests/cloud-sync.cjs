const assert = require('node:assert/strict')
const load = require('./helpers/load-typescript.cjs')
const { canonical, reconcile, syncServerUrl, validateRecords } = load('src/cloudSync.ts', {}, { URL })
const key = 'day:2026-10-24'
const day = text => ({ date: '2026-10-24', tasks: [{ id: 'task_a', text, status: 'todo', subtasks: [] }] })
const record = (payload, revision = 1, deleted = false) => ({ key, payload, revision, deleted, updatedAt: '', mutationId: 'mutation_1234567890' })
const base = payload => ({ [key]: { payload, revision: 1, deleted: false } })
assert.equal(canonical({ a: 1, b: 2 }), canonical({ b: 2, a: 1 }))
assert.notEqual(canonical([1, 2]), canonical([2, 1]))
assert.equal(reconcile({ [key]: day('Local') }, [], {})[0].kind, 'push')
assert.equal(reconcile({}, [record(day('Cloud'))], {})[0].kind, 'pull')
assert.equal(reconcile({ [key]: day('Original') }, [record(day('Cloud'), 2)], base(day('Original')))[0].kind, 'pull')
assert.equal(reconcile({ [key]: day('Local') }, [record(day('Original'))], base(day('Original')))[0].kind, 'push')
assert.equal(reconcile({ [key]: day('Local') }, [record(day('Cloud'), 2)], base(day('Original')))[0].kind, 'conflict')
assert.equal(reconcile({ [key]: day('Local') }, [record(day('Cloud'))], {})[0].kind, 'conflict')
assert.equal(reconcile({ [key]: day('Same') }, [record(day('Same'), 3)], base(day('Old')))[0].kind, 'ack')
assert.equal(reconcile({ [key]: day('Offline edit') }, [record(null, 2, true)], base(day('Original')))[0].kind, 'conflict')
assert.equal(reconcile({}, [record(day('Original'))], base(day('Original')))[0].kind, 'push')
assert.equal(reconcile({ [key]: day('Original') }, [record(null, 2, true)], base(day('Original')))[0].kind, 'pull')
assert.equal(reconcile({ [key]: { date: '2026-10-24', tasks: [] } }, [record(day('Cloud'))], {})[0].kind, 'pull')
assert.equal(reconcile({ [key]: day('Original') }, [], base(day('Original')))[0].kind, 'conflict')
const mission = { id: 'focus_a' }
const focusRecord = { ...record(mission), key: 'focus:focus_a' }
assert.deepEqual(JSON.parse(JSON.stringify(reconcile({}, [focusRecord], { 'focus:focus_a': { payload: mission, revision: 1, deleted: false } }))), [])
assert.throws(() => syncServerUrl('http://example.com'))
assert.throws(() => syncServerUrl('https://user:secret@example.com'))
assert.equal(syncServerUrl('https://example.com/'), 'https://example.com')
assert.equal(syncServerUrl('http://localhost:8080'), 'http://localhost:8080')
assert.throws(() => validateRecords([{ ...record(day('a')), key: '../users/bob' }]))
assert.throws(() => validateRecords([record(day('a')), record(day('b'))]))
assert.throws(() => validateRecords([record({})]))
assert.throws(() => validateRecords([record({ date: '2026-10-23', tasks: [] })]))
assert.throws(() => validateRecords([{ ...record({ targets: [] }), key: 'goals' }]))
assert.throws(() => validateRecords([record({ date: '2026-10-24', tasks: [{ ...day('bad').tasks[0], finish: { doneWhen: 0 } }] })]))
assert.equal(validateRecords([record(day('valid'))]).length, 1)
assert.equal(reconcile({ [key]: { date: '2026-10-24', tasks: [] } }, [record(null, 2, true)], { [key]: { payload: null, revision: 2, deleted: true } })[0].kind, 'ack')
console.log('Cloud sync: three-way reconciliation, first-link safety, deletion conflicts, retention and origin validation passed')
