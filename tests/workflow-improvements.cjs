const assert = require('node:assert/strict')
const load = require('./helpers/load-typescript.cjs')
const { archiveRows, searchArchive, archiveSummary } = load('src/taskArchive.ts')
const { nextOccurrence, readRoutineSchedules, routineTaskId } = load('src/routines.ts')
const { validateDayPlan } = load('src/taskPlanning.ts')
const task = (id, status = 'todo', children = []) => ({ id, text: id, status, subtasks: children })
const dates = [
  { date: '2026-10-30', tasks: [task('Write paper', 'partial', [task('Read sources', 'done')]), task('Send invoice', 'done'), task('Old approach', 'stopped')] },
  { date: '2026-10-29', tasks: [task('Plan trip')] },
  { date: '2026-10-30', tasks: [task('Wrong duplicate date')] },
]
const rows = archiveRows(dates)
assert.equal(rows.length, 5)
assert.equal(searchArchive(rows, 'paper sources')[0].rootId, 'Write paper')
assert.equal(searchArchive(rows, 'INVOICE', 'done').length, 1)
assert.equal(searchArchive(rows, '', 'open').length, 2)
const summary = archiveSummary(rows, '2026-10-30', '2026-10-30')
assert.equal(summary.done, 1); assert.equal(summary.open, 1); assert.equal(summary.stopped, 1)
assert.equal(summary.stepsDone, 1); assert.equal(summary.stepsTotal, 1)
const schedule = (cadence, extra = {}) => ({ cadence, anchor: '2026-10-30', paused: false, ...extra })
assert.equal(nextOccurrence(schedule('daily'), '2026-10-30'), '2026-10-30')
assert.equal(nextOccurrence(schedule('daily', { handledThrough: '2026-10-30' }), '2026-10-30'), '2026-10-31')
assert.equal(nextOccurrence(schedule('weekdays'), '2026-10-31'), '2026-11-02')
assert.equal(nextOccurrence(schedule('weekly'), '2026-11-01'), '2026-11-06')
assert.equal(nextOccurrence(schedule('daily'), '2026-12-31'), '2026-12-31', 'No backlog flood after absence')
assert.equal(nextOccurrence(schedule('daily', { handledThrough: '2026-12-31' }), '2026-12-31'), '2027-01-01')
assert.equal(nextOccurrence(schedule('daily', { paused: true }), '2026-10-30'), null)
assert.equal(nextOccurrence(schedule('manual'), '2026-10-30'), null)
assert.equal(nextOccurrence(schedule('daily', { handledThrough: '2026-11-01' }), '2026-10-30'), '2026-11-02', 'Skipped occurrence is not recreated')
assert.equal(routineTaskId('阅读', '2026-10-30'), routineTaskId('阅读', '2026-10-30'))
assert.notEqual(routineTaskId('r1', '2026-10-30'), routineTaskId('r1', '2026-10-31'))
assert.ok(routineTaskId('a'.repeat(300), '2026-10-30').length < 200)
assert.equal(readRoutineSchedules(null).constructor, undefined)
assert.equal(readRoutineSchedules('{}').__proto__, undefined)
assert.throws(() => readRoutineSchedules('{'))
assert.throws(() => readRoutineSchedules(JSON.stringify({ r: schedule('daily', { anchor: '2026-02-30' }) })))
assert.throws(() => readRoutineSchedules(JSON.stringify({ r: schedule('yearly') })))
const context = { date: '2026-10-30', start: '09:00', end: '17:00', machines: [], tasks: [{ ...task('t'), todaySubtasks: [], otherSubtasks: [] }], unavailable: [{ start: '12:00', end: '13:00' }], estimates: { t: 30 } }
const proposal = (time, endTime) => ({ schedule: [{ taskId: 't', time, endTime, action: 'Draft', assignedTo: 'human' }] })
assert.equal(validateDayPlan(proposal('11:30', '12:00'), context).schedule.length, 1)
assert.throws(() => validateDayPlan(proposal('11:45', '12:15'), context), /unavailable/)
assert.throws(() => validateDayPlan(proposal('09:00', '09:45'), context), /budget/)
assert.throws(() => validateDayPlan(proposal('09:00', '09:15'), { ...context, unavailable: [{ start: '14:00', end: '13:00' }] }), /unavailable/)
console.log('Passed archive search/canonical counting, recurrence calendar/skip/identity/recovery, and constrained planning checks')
